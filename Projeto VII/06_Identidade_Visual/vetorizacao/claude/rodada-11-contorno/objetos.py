def P(*pts): return " ".join(f"{x:.1f},{y:.1f}" for x, y in pts)
def arco(c, r, a0, a1, n=8):
    """Pontos sobre um círculo, de a0 a a1 graus (0 = direita, sentido horário)."""
    return [(c[0] + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)), c[1] + r * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]
def mix(A, B, t): return [(a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t) for a, b in zip(A, B)]

